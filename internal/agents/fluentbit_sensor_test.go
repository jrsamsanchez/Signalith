func sensorConfig(t *testing.T, o Options) *Agent {
	t.Helper()
	o.OS, o.LinuxSource = "linux", "sensor"
	if o.ServerURL == "" {
		o.ServerURL = "https://siem.example.com:8080"
	}
	o.Token = TokenPlaceholder
	o.CA = "-----BEGIN CERTIFICATE-----\nMIIB\n-----END CERTIFICATE-----"
	a, err := Generate(o)
	if err != nil {
		t.Fatal(err)
	}
	return a
}

func TestGenerateSensor(t *testing.T) {
	a := sensorConfig(t, Options{Zeek: true, Suricata: true})
	for _, want := range []string{
		"# Signalith agent for a network sensor (Zeek, Suricata). Generated by Signalith.\n",
		line("Tag", "zeek.*"),
		line("Path", "/opt/zeek/logs/current/*.log"),
		line("Exclude_Path", "*loaded_scripts.log,*packet_filter.log,*stderr.log,*stdout.log,*print.log"),
		line("DB", "/var/lib/fluent-bit/signalith-zeek.db"),
		line("Tag", "suricata.eve"),
		line("Path", "/var/log/suricata/eve.json"),
		line("DB", "/var/lib/fluent-bit/signalith-suricata.db"),
		line("Buffer_Max_Size", "500k"),
		line("storage.total_limit_size", "4G"),
		line("Skip_Long_Lines", "On"),
		line("Mem_Buf_Limit", "50MB"),
		line("Rotate_Wait", "30"),
		line("Exclude", `log "event_type":"(flow|netflow|dns|http|tls)"`),
		line("Match", "zeek.*") + line("hostname_key", "hostname"),
		line("Match", "suricata.*") + line("hostname_key", "hostname"),
		line("Header", "Authorization Bearer "+TokenPlaceholder),
		line("tls.ca_file", LinuxCAPath),
		line("tls.verify", "On"),
		line("tls.vhost", "siem.example.com"),
	} {
		if !strings.Contains(a.Config, want) {
			t.Errorf("config missing %q:\n%s", want, a.Config)
		}
	}
	// Only the sensor's logs: no auth log, journal or audit log inputs,
	// and no parser (Signalith decodes the lines).
	for _, not := range []string{"auth.log", "systemd", "linux.", "audit", "Parser"} {
		if strings.Contains(a.Config, not) {
			t.Errorf("config has %q", not)
		}
	}
	steps := strings.Join(a.Steps, "\n")
	for _, want := range []string{"json-logs", "echo '@load policy/tuning/json-logs' | sudo tee -a /opt/zeek/share/zeek/site/local.zeek && sudo /opt/zeek/bin/zeekctl deploy",
		"community-id to true", "community-id-logging", "run sudo /opt/zeek/bin/zeekctl deploy", "search vendor_product IN (Zeek, Suricata))", "only new log lines"} {
		if !strings.Contains(steps, want) {
			t.Errorf("steps missing %q:\n%s", want, steps)
		}
	}
	if strings.Contains(steps, "auditd") {
		t.Error("steps mention auditd")
	}
	if a.CAStep == 0 || a.ConfigStep != a.CAStep+1 || !strings.Contains(a.Steps[a.ConfigStep-1], "fluent-bit.conf") {
		t.Errorf("CA step %d, config step %d", a.CAStep, a.ConfigStep)
	}

	// Zeek only: no Suricata input, so no filter for it either.
	z := sensorConfig(t, Options{Zeek: true})
	if strings.Contains(z.Config, "suricata") || strings.Contains(strings.Join(z.Steps, "\n"), "Suricata set") {
		t.Errorf("Zeek only config has Suricata:\n%s", z.Config)
	}
	// Suricata only: every event type is sent.
	s := sensorConfig(t, Options{Suricata: true})
	if strings.Contains(s.Config, "zeek") || strings.Contains(s.Config, "grep") || strings.Contains(strings.Join(s.Steps, "\n"), "json-logs") {
		t.Errorf("Suricata only config:\n%s", s.Config)
	}
	// Both, with Suricata's protocol logs too.
	p := sensorConfig(t, Options{Zeek: true, Suricata: true, SuricataProtocols: true})
	if strings.Contains(p.Config, "grep") {
		t.Errorf("protocol logs filtered:\n%s", p.Config)
	}
	// Paths as given (Security Onion, a source install).
	c := sensorConfig(t, Options{Zeek: true, Suricata: true, ZeekDir: "/nsm/zeek/logs/current/", EVEPath: "/nsm/suricata/eve-2.json"})
	for _, want := range []string{line("Path", "/nsm/zeek/logs/current/*.log"), line("Path", "/nsm/suricata/eve-2.json")} {
		if !strings.Contains(c.Config, want) {
			t.Errorf("config missing %q", want)
		}
	}
	// Security Onion's Zeek and Suricata already write JSON with
	// Community ID: no steps to change them, and no zeekctl.
	cs := strings.Join(c.Steps, "\n")
	if !strings.Contains(cs, "already writes JSON") || strings.Contains(cs, "zeekctl") || strings.Contains(cs, "Community ID") {
		t.Errorf("Security Onion steps:\n%s", cs)
	}
	src := sensorConfig(t, Options{Zeek: true, ZeekDir: "/usr/local/zeek/logs/current"})
	if ss := strings.Join(src.Steps, "\n"); !strings.Contains(ss, "/usr/local/zeek/share/zeek/site/local.zeek && sudo /usr/local/zeek/bin/zeekctl deploy") {
		t.Errorf("source install steps:\n%s", ss)
	}
	if !strings.Contains(sensorConfig(t, Options{Zeek: true}).Steps[len(sensorConfig(t, Options{Zeek: true}).Steps)-1], "vendor_product IN (Zeek))") {
		t.Error("Zeek only search")
	}
	u := sensorConfig(t, Options{Zeek: true, ZeekDir: "/data/zeek-logs"})
	if us := strings.Join(u.Steps, "\n"); !strings.Contains(us, "in Zeek's install folder") || strings.Contains(us, "sudo zeekctl") {
		t.Error("local.zeek step for an unusual folder")
	}
}

func TestGenerateSensorRejects(t *testing.T) {
	for _, c := range []struct {
		o     Options
		field string
	}{
		{Options{}, "tools"},
		{Options{Zeek: true, ZeekDir: "opt/zeek/logs"}, "zeek_dir"},
		{Options{Zeek: true, ZeekDir: "/opt/zeek logs"}, "zeek_dir"},
		{Options{Zeek: true, ZeekDir: "/opt/zeek\n[OUTPUT]"}, "zeek_dir"},
		{Options{Zeek: true, ZeekDir: "/opt/../etc"}, "zeek_dir"},
		{Options{Zeek: true, ZeekDir: "/opt/$HOME"}, "zeek_dir"},
		{Options{Zeek: true, ZeekDir: "/" + strings.Repeat("a", 200)}, "zeek_dir"},
		{Options{Zeek: true, ZeekDir: `C:\zeek`}, "zeek_dir"},
		{Options{Suricata: true, EVEPath: "eve.json"}, "eve_path"},
		{Options{Suricata: true, EVEPath: "/var/log/*.json"}, "eve_path"},
		{Options{Zeek: true, Suricata: true, EVEPath: "/var/log/suricata/eve.json\r\n"}, "eve_path"},
	} {
		o := c.o
		o.OS, o.LinuxSource, o.ServerURL, o.Token = "linux", "sensor", "https://siem.example.com", "t"
		_, err := Generate(o)
		var fe *FieldError
		if !errors.As(err, &fe) || fe.Field != c.field {
			t.Errorf("%+v: %v, want an error for %s", c.o, err, c.field)
			continue
		}
		if c.field != "tools" && !strings.Contains(err.Error(), map[string]string{"zeek_dir": "Zeek logs folder", "eve_path": "Suricata EVE file"}[c.field]) {
			t.Errorf("error does not name the field: %v", err)
		}
	}
	// A path for a tool that is not picked is not checked.
	if _, err := Generate(Options{OS: "linux", LinuxSource: "sensor", Suricata: true, ZeekDir: "bad path", ServerURL: "https://siem.example.com", Token: "t"}); err != nil {
		t.Error(err)
	}
	// The 200-byte limit is inclusive.
	if err := sensorPath("/" + strings.Repeat("a", 199)); err != nil {
		t.Error(err)
	}
}

func TestGenerateSensorLeavesOtherSourcesAlone(t *testing.T) {
	for _, src := range []string{"", "file", "journal", "wazuh"} {
		a, err := Generate(Options{OS: "linux", LinuxSource: src, ServerURL: "http://192.0.2.1:8080", Token: "t", Zeek: true, Suricata: true})
		if err != nil {
			t.Fatal(err)
		}
		if l := strings.ToLower(a.Config + strings.Join(a.Steps, "\n")); strings.Contains(l, "zeek") || strings.Contains(l, "suricata") {
			t.Errorf("source %q mentions the sensor", src)
		}
	}
}
